import csv,glob,json,collections,math
from pathlib import Path
out={}
# Disjoint source ages; require both sexes and every constituent age.
age_bins = [(f'{lo}–{lo+9} Jahre', ids) for lo, ids in [
 (0,[1,6]), (10,[7,8]), (20,[9,10]), (30,[11,12]),
 (40,[13,14]), (50,[15,16]), (60,[17,18]), (70,[19,20]),
 (80,[30,31])]] + [('90+ Jahre',[32,235])]
for key,pattern in [('global','Data/IHME*14ca*/*.csv'),('de','Data/IHME*066*/*.csv')]:
 rows=list(csv.DictReader(open(glob.glob(pattern)[0])))
 years=list(range(1980,2024)); causes={}
 groups=collections.defaultdict(dict)
 for r in rows:
  if r['measure_id']=='1' and r['metric_id']=='1' and int(r['year'])>=1980:
   cell=(r['cause_name'],int(r['age_id']),int(r['year']))
   assert r['sex_id'] not in groups[cell],cell
   groups[cell][r['sex_id']]=float(r['val'])
 for cause in sorted({r['cause_name'] for r in rows}):
  cells=[]
  for name,age_ids in age_bins:
   line=[]
   for y in years:
    parts=[groups.get((cause,aid,y),{}) for aid in age_ids]
    line.append(sum(sum(sexes.values()) for sexes in parts) if all(set(sexes)=={'1','2'} for sexes in parts) else None)
   cells.append(line)
  causes[cause]=cells
 out[key]={'years':years,'ages':[name for name,_ in age_bins],'causes':causes}
# Unterkategorien Atemwege/Tuberkulose (nur Deutschland) aus den 5-Jahres-CSVs in Data/Project Data.
# 70-74 (age_id 19) und 65-69 (18) kommen aus der Nachlieferung bafd9bed; 65-74 (232) dient als Gegenprobe.
new_dir = Path(__file__).resolve().parents[1] / 'Data' / 'Project Data'
new = {}
for f in sorted(new_dir.glob('**/*.csv')):
 for r in csv.DictReader(open(f, encoding='utf-8-sig')):
  if r['measure_id']=='1' and r['metric_id']=='1':
   k=(r['cause_name'],int(r['age_id']),int(r['year']),r['sex_id'])
   v=float(r['val'])
   if k in new: assert math.isclose(new[k],v,rel_tol=1e-12,abs_tol=1e-12),k  # Ueberschneidung muss identisch sein
   new[k]=v
new_causes=sorted({k[0] for k in new})
old_de={c:[row[:] for row in rows] for c,rows in out['de']['causes'].items()}
def new_cell(cause,age_id,y):
 return sum(new[(cause,age_id,y,s)] for s in ('1','2'))
def new_line(cause,age_ids,y):
 return sum(new_cell(cause,aid,y) for aid in age_ids)
for cause in new_causes:
 for y in range(1980,2024):
  assert math.isclose(new_cell(cause,232,y),new_cell(cause,18,y)+new_cell(cause,19,y),rel_tol=1e-9,abs_tol=1e-9),(cause,y)
de=out['de']
for cause in new_causes:
 de['causes'][cause]=[[new_line(cause,ids,y) for y in de['years']] for _,ids in age_bins]
# Pruefung: die schon vorhandene Zeile 'Infektionen der Atemwege und Tuberkulose' muss mit den neuen Dateien identisch sein.
rc='Infektionen der Atemwege und Tuberkulose'
for a,_ in enumerate(age_bins):
 for i,y in enumerate(de['years']):
  assert math.isclose(old_de[rc][a][i],de['causes'][rc][a][i],rel_tol=1e-9,abs_tol=1e-9),(rc,a,y)
# Pruefung: Unterkategorien summieren sich je Altersgruppe und Jahr zur Oberkategorie.
parts=[c for c in new_causes if c not in (rc,'Tuberkulose')]
for a,_ in enumerate(age_bins):
 for i,y in enumerate(de['years']):
  assert math.isclose(sum(de['causes'][c][a][i] for c in parts),de['causes'][rc][a][i],rel_tol=1e-9,abs_tol=1e-9),(a,y)
Path('age-data.js').write_text('// Generated by tools/build_age_data.py from the IHME GBD 2023 age CSVs (Data/ and Data/Project Data/). Both sexes = male + female point estimates.\n// Ten-year age bins; missing constituent ages or sex pairs stay null. Uncertainty bounds are not aggregated.\n// Germany additionally holds the respiratory/TB subcategories (Data/Project Data).\nconst AGE_DATA = '+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
print('Generated age-data.js; missing cells:',sum(x is None for d in out.values() for rows in d['causes'].values() for row in rows for x in row))
